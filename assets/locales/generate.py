# Pseudo-locale for layout-overflow testing: long strings with wide glyphs.
PSEUDO = {k: f"[⟦{v} ⟧⟧⟧]" for k, v in EN.items()}
TRANSLATIONS["qps-ploc"] = PSEUDO


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    for locale, strings in sorted(TRANSLATIONS.items()):
        unknown = set(strings) - set(KEYS)
        if unknown:
            raise SystemExit(f"{locale}: unknown keys {sorted(unknown)}")
        path = os.path.join(here, f"{locale}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(
                {k: strings[k] for k in KEYS if k in strings},
                fh,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            fh.write("\n")
    print(f"wrote {len(TRANSLATIONS)} catalogs")


if __name__ == "__main__":
    main()
