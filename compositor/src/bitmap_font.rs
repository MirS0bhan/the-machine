pub fn draw_text(px: &mut PixelBackend, x: i32, y: i32, text: &str, r: u8, g: u8, b: u8) {
    let scale = 2u32;
    let mut cursor = x;
    for ch in text.chars().take(120) {
        let rows = glyph(ch);
        for (row, bits) in rows.iter().enumerate() {
            let row = row as u32;
            for col in 0..W {
                if bits & (1 << (W - 1 - col)) != 0 {
                    px.fill_rect(
                        cursor + (col * scale) as i32,
                        y + (row * scale) as i32,
                        scale,
                        scale,
                        r,
                        g,
                        b,
                    );
                }
            }
        }
        cursor += (W * scale + scale) as i32;
    }
}

