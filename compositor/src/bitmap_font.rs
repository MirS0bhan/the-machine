/// Draw text at default body scale (2×).
#[allow(dead_code)]
pub fn draw_text(px: &mut PixelBackend, x: i32, y: i32, text: &str, r: u8, g: u8, b: u8) {
    draw_text_scaled(px, x, y, text, r, g, b, 2);
}

/// Draw text with an explicit pixel scale (title ≈ 4, label ≈ 3, caption ≈ 2).
pub fn draw_text_scaled(
    px: &mut PixelBackend,
    x: i32,
    y: i32,
    text: &str,
    r: u8,
    g: u8,
    b: u8,
    scale: u32,
) {
    let scale = scale.max(1);
    let mut cursor = x;
    for ch in text.chars().take(160) {
        let rows = glyph(ch);
        for (row, bits) in rows.iter().enumerate() {
            let row = row as u32;
            for col in 0..W {
                if bits & (1 << (W - 1 - col)) != 0 {
                    px.fill_rect(
                        cursor + (col * scale) as i32,
                        y + (row * scale) as i32,
                        scale,
                        scale,
                        [r, g, b],
                    );
                }
            }
        }
        cursor += (W * scale + scale) as i32;
    }
}

/// Approximate advance width for layout clipping.
#[allow(dead_code)]
pub fn text_width(text: &str, scale: u32) -> u32 {
    let scale = scale.max(1);
    let n = text.chars().count().min(160) as u32;
    n * (W * scale + scale)
}

